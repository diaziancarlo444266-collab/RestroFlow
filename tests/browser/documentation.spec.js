import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('capture documentation screenshots with isolated demo accounts', async ({ page }) => {
    test.skip(process.env.DOC_SCREENSHOTS !== '1', 'Run explicitly to refresh documentation assets.');
    test.setTimeout(180000);
    await page.setViewportSize({ width: 1440, height: 1000 });
    const shot = async name => {
        await page.evaluate(() => document.fonts.ready);
        await page.screenshot({ path: `docs/screenshots/${name}.png`, fullPage: true, animations: 'disabled' });
    };
    const ready = async () => {
        await expect(page.getByText(/^Loading /)).toHaveCount(0);
        await expect(page.getByRole('alert').filter({ hasText: 'Unable' })).toHaveCount(0);
    };
    await page.goto('/login');
    await shot('01-login');
    await page.getByRole('link', { name: 'Forgot password?' }).click();
    await shot('02-forgot-password');
    await page.goto('/register');
    await shot('03-register');
    await page.getByLabel('Name', { exact: true }).fill('Demo Customer');
    await page.getByLabel('Email', { exact: true }).fill(`documentation${Date.now()}@browser.test`);
    await page.getByLabel('Password (at least 8 characters)', { exact: true }).fill('DemoPassword123!');
    await page.getByLabel('Confirm password', { exact: true }).fill('DemoPassword123!');
    await page.getByRole('button', { name: 'Register', exact: true }).click();
    await expect(page.getByLabel('Verification code')).toBeVisible();
    await shot('04-otp');
    const codes = [...readFileSync('storage/logs/laravel.log', 'utf8').matchAll(/<strong>([0-9]{6})<\/strong>/g)];
    await page.getByLabel('Verification code').fill(codes.at(-1)[1]);
    await page.getByRole('button', { name: 'Verify and sign in' }).click();
    await expect(page.getByRole('button', { name: 'New Order', exact: true })).toBeVisible();
    await ready();
    await page.getByRole('button', { name: 'New Order', exact: true }).click();
    await page.getByLabel('Menu Item', { exact: true }).selectOption({ index: 1 });
    await page.getByLabel('Quantity', { exact: true }).fill('2');
    await shot('05-order-form');
    await page.getByRole('button', { name: 'Save Order', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await ready();
    await page.getByRole('button', { name: 'My Reservations', exact: true }).click();
    await page.getByRole('button', { name: 'Add Reservation', exact: true }).click();
    await page.getByLabel('Phone Number').fill('09000000000');
    await page.getByLabel('Table', { exact: true }).selectOption({ index: 1 });
    await page.getByLabel('Date', { exact: true }).fill('2026-10-20');
    await page.getByLabel('Time', { exact: true }).fill('18:30');
    await page.getByLabel('Guests', { exact: true }).fill('2');
    await shot('06-reservation-form');
    await page.getByRole('button', { name: 'Save Reservation', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await ready();
    await shot('07-my-reservations');
    await page.getByRole('button', { name: 'My Orders', exact: true }).click();
    await ready();
    await shot('08-my-orders');
    await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
    await ready();
    await shot('09-customer-dashboard');
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByLabel('Email or username').fill('admin@browser.test');
    await page.getByLabel('Password', { exact: true }).fill('BrowserTestPassword123!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Inventory', exact: true })).toBeVisible();
    await ready();
    await shot('10-admin-dashboard');
    await page.getByRole('button', { name: 'Reservations', exact: true }).click();
    await ready();
    await page.getByRole('row').filter({ hasText: 'Demo Customer' }).first().getByRole('button', { name: 'Edit Reservation', exact: true }).click();
    await page.getByLabel('Status', { exact: true }).selectOption('Confirmed');
    await shot('11-admin-confirm');
    await page.getByRole('button', { name: 'Save Reservation', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await ready();
    await shot('12-admin-reservations');
    await page.getByRole('button', { name: 'Inventory', exact: true }).click();
    await page.getByRole('button', { name: 'Add Item', exact: true }).click();
    await page.getByLabel('Item Name', { exact: true }).fill('Documentation Rice');
    await page.getByLabel('Quantity', { exact: true }).fill('2');
    await page.getByLabel('Unit', { exact: true }).fill('kg');
    await page.getByLabel('Reorder At', { exact: true }).fill('5');
    await page.getByRole('button', { name: 'Save Item', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await ready();
    await shot('13-admin-inventory');
    await page.getByRole('button', { name: 'Sign out', exact: true }).click();
    await page.getByLabel('Email or username').fill('staff@browser.test');
    await page.getByLabel('Password', { exact: true }).fill('BrowserTestPassword123!');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.getByRole('button', { name: 'Inventory', exact: true }).click();
    await ready();
    await expect(page.getByRole('button', { name: 'Delete Item', exact: true })).toHaveCount(0);
    await shot('14-staff-inventory');
});
